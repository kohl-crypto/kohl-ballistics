#!/usr/bin/env python3
"""Regenerate the expected numbers in solver-reference.json from py-ballisticcalc, an independent,
widely used open-source solver. Only needed when adding or changing a test shot; the build itself
doesn't need Python packages.
Usage: pip install py-ballisticcalc==3.1.0 && python3 source/check/make_reference.py"""
import json, os
import py_ballisticcalc as pbc
from py_ballisticcalc import (Ammo, Atmo, Calculator, DragModel, Shot, TableG1, TableG7, Weapon, Wind,
                              Angular, Distance, Pressure, Temperature, Velocity, Weight)

HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(HERE, 'solver-reference.json')
TABLES = {"G1": TableG1, "G7": TableG7}


def atmo(e):
    kw = dict(altitude=Distance.Foot(e["altFt"]), temperature=Temperature.Fahrenheit(e["tempF"]), humidity=e["rh"])
    if e.get("pressure"):  # station pressure; 0 means "estimate from altitude", same as the app
        kw["pressure"] = Pressure.InHg(e["pressure"])
    return Atmo(**kw)


def run(s):
    L, e = s["load"], s["env"]
    dm_kw = dict(weight=Weight.Grain(L["weight"]), diameter=Distance.Inch(L.get("diameter", 0.308)))
    w_kw = dict(sight_height=Distance.Inch(L["sightHeight"]))
    if e.get("spin", True) and L.get("twist") and L.get("length"):
        dm_kw["length"] = Distance.Inch(L["length"])
        w_kw["twist"] = Distance.Inch(L["twist"])
    ammo = Ammo(DragModel(L["bc"], TABLES[L["model"]], **dm_kw), Velocity.FPS(L["mv"]))
    weapon = Weapon(**w_kw)
    calc = Calculator()
    calc.set_weapon_zero(Shot(weapon=weapon, ammo=ammo, atmo=atmo(s["zeroEnv"])), Distance.Yard(L["zeroRange"]))
    # The app's clock is where the wind comes FROM, 3 o'clock = from the right. py-ballisticcalc measures
    # the other way round (90 deg = from the left), so mirror the clock.
    winds = [Wind(Velocity.MPH(e["windMph"]), Angular.OClock((12 - e["windClock"]) % 12))] if e["windMph"] else []
    shot = Shot(weapon=weapon, ammo=ammo, atmo=atmo(e), look_angle=Angular.Degree(e["angle"]), winds=winds)
    pts = calc.fire(shot, trajectory_range=Distance.Yard(max(s["ranges"]) * 1.1), trajectory_step=Distance.Yard(1)).records
    out = []
    for r in s["ranges"]:  # the app's ranges and drops are measured along the line of sight
        a, b = next((a, b) for a, b in zip(pts, pts[1:]) if (a.slant_distance >> Distance.Yard) <= r <= (b.slant_distance >> Distance.Yard))
        da, db = a.slant_distance >> Distance.Yard, b.slant_distance >> Distance.Yard
        f = (r - da) / (db - da) if db > da else 0
        lerp = lambda u, v: round(u + f * (v - u), 4)
        out.append(dict(r=r, dropIn=lerp(a.slant_height >> Distance.Inch, b.slant_height >> Distance.Inch),
                        windIn=lerp(a.windage >> Distance.Inch, b.windage >> Distance.Inch),
                        v=lerp(a.velocity >> Velocity.FPS, b.velocity >> Velocity.FPS), tof=lerp(a.time, b.time)))
    return out


with open(REF, encoding="utf-8") as f:
    ref = json.load(f)
for s in ref["shots"]:
    s["expected"] = run(s)
ref["source"] = f"py-ballisticcalc {pbc.__version__} (default engine), generated by make_reference.py"
with open(REF, "w", encoding="utf-8", newline="\n") as f:
    f.write(json.dumps(ref, indent=2) + "\n")
print('wrote', len(ref["shots"]), 'shots to', REF)
